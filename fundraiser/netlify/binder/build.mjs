// Packs the MHS Secret Binder page into the binder function so it is only served behind the team code.
// After editing netlify/binder/index.html, run: node netlify/binder/build.mjs
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("./index.html", import.meta.url), "utf8");
writeFileSync(
  new URL("../lib/binder-page.mts", import.meta.url),
  `// Generated by netlify/binder/build.mjs from netlify/binder/index.html. Do not edit by hand.\nexport default ${JSON.stringify(html)};\n`,
);
console.log(`binder-page.mts written (${html.length} characters)`);
